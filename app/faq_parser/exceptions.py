"""
    Модуль пользовательских исключений для компонента парсинга FAQ.

    Иерархия исключений позволяет точно идентифицировать ошибки на разных этапах:
    загрузки веб-страниц, синтаксического анализа HTML-структуры и сериализации данных.
"""

# Локальные импорты
from app.exceptions import AppError




class FAQParserError(AppError):
    """Базовое исключение для всех ошибок парсера FAQ."""
    pass


class DownloadError(FAQParserError):
    """Исключение, возникающее при ошибках загрузки или рендеринга веб-страниц."""
    pass


class ExtractionError(FAQParserError):
    """Исключение, возникающее при ошибках извлечения и парсинга данных из HTML."""
    pass


class SerializationError(FAQParserError):
    """Исключение, возникающее при ошибках сохранении или сериализации данных в файл."""
    pass
