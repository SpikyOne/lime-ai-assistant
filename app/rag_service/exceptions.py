"""
    Модуль пользовательских исключений для компонента RAG-сервиса.

    Иерархия исключений для обработки ошибок векторного поиска в ChromaDB,
    валидации входящих пользовательских запросов и взаимодействия
    с локальным LLM-провайдером (Ollama).
"""

# Локальные импорты
from app.exceptions import AppError




class RAGServiceError(AppError):
    """Базовое исключение для всех ошибок модуля RAG-сервиса."""
    pass


class ChromaConnectionError(RAGServiceError):
    """Исключение, возникающее при отсутствии подключения или ошибках доступа к ChromaDB."""
    pass


class InvalidQueryError(RAGServiceError):
    """Исключение, возникающее при передаче невалидного или пустого пользовательского запроса."""
    pass



# ==============================================================================
# Ошибки генерации и взаимодействия с LLM (Ollama)
# ==============================================================================
class LLMError(RAGServiceError):
    """Базовое исключение для ошибок модуля языковой модели (LLM)."""
    pass


class OllamaConnectionError(LLMError):
    """Исключение, возникающее при отсутствии связи с локальным сервисом Ollama."""
    pass


class OllamaDownloadError(LLMError):
    """Исключение, возникающее при ошибках загрузки весов модели в Ollama."""
    pass
